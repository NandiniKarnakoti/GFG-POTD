# Problem: Character at Position in Infinite String
# Difficulty: Medium
# Date: 23 November 2026
# Language: Python

"""
Problem:
Find the character at the given 1-based position in an
infinite string generated by repeatedly appending i '$'
characters followed by the reverse of the current string.
"""

# ---------------------------------------------------
# Approach: Length Tracking + Reverse Position Mapping
# Time Complexity: O(log(pos))
# Space Complexity: O(log(pos))
# ---------------------------------------------------

class Solution:
    def posInfinite(self, s: str, pos: int) -> str:
        # code here
        lengths = [len(s)]
        i = 1
        while lengths[-1] < pos:
            lengths.append(2 * lengths[-1] + i)
            i += 1
        while pos > len(s):
            old_len = lengths[-2]
            step = len(lengths) - 1
            if pos <= old_len:
                lengths.pop()
            elif pos <= old_len + step:
                return '$'
            else:
                pos = 2 * old_len + step - pos + 1
                lengths.pop()
        return s[pos - 1]
